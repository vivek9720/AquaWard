pub fn pattern_by_code(code: u16) -> Option<&'static IncidentPattern> {
    INCIDENT_PATTERNS
        .iter()
        .find(|pattern| pattern.code == code)
}

pub fn incident_load(kind: u8) -> u32 {
    INCIDENT_PATTERNS
        .iter()
        .filter(|pattern| pattern.kind == kind)
        .fold(0u32, |acc, pattern| {
            acc + pattern.severity as u32 * pattern.response_units as u32
        })
}
