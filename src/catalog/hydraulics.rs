pub fn class_by_id(class_id: u16) -> Option<&'static PipeClass> {
    PIPE_CLASSES.iter().find(|class| class.class_id == class_id)
}

pub fn friction_hint(material: u8, diameter: u16) -> u16 {
    let mut best = 110u16;
    for class in PIPE_CLASSES
        .iter()
        .filter(|class| class.material == material)
    {
        if diameter >= class.min_diameter_mm && diameter <= class.max_diameter_mm {
            best = best.saturating_add(class.friction / 8);
        }
    }
    best
}
