pub fn limit_by_code(code: u16) -> Option<&'static ChemicalLimit> {
    CHEMICAL_LIMITS.iter().find(|limit| limit.code == code)
}

pub fn blended_alarm(group: u8, observed: u32) -> u32 {
    let mut acc = observed.wrapping_mul(17);
    for limit in CHEMICAL_LIMITS.iter().filter(|limit| limit.group == group) {
        acc = acc.wrapping_add(limit.alarm_ppb ^ ((limit.warn_ppb + 1) * (limit.decay as u32 + 1)));
    }
    acc
}
